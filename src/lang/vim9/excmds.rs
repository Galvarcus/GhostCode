/// FUNCTION: Whether Vim defines a command of this name, written whole.
pub fn has(name: &str) -> bool {
    NAMES
        .binary_search_by(|(whole, _)| (*whole).cmp(name))
        .is_ok()
}

/// FUNCTION: The command a word names, written whole or abbreviated,
/// and `None` for a word that names none.
///
/// The names that share a prefix stand together in a sorted table, so
/// the search is a binary one and then a walk of that run alone. Where
/// several commands admit the same prefix, the first of the run answers,
/// because the help file records no precedence between them and every
/// caller asks only whether a word is a command.
pub fn canonical(word: &str) -> Option<&'static str> {
    if word.len() < MIN_ABBREV {
        return None;
    }

    let at = NAMES.partition_point(|(whole, _)| *whole < word);

    NAMES[at..]
        .iter()
        .take_while(|(whole, _)| whole.starts_with(word))
        .find(|(_, least)| word.len() >= *least)
        .map(|(whole, _)| *whole)
}

#[cfg(test)]
mod tests {
    use super::canonical;
    use super::NAMES;

    /// The lookup is a binary search, which answers an unordered table
    /// wrongly rather than slowly, and a name listed twice would mean
    /// the help file was read with the wrong bounds.
    #[test]
    fn the_table_is_ordered_and_each_name_appears_once() {
        assert!(NAMES.windows(2).all(|pair| pair[0].0 < pair[1].0));
    }

    /// A scope prefix is a single letter, and a single letter is left
    /// out of the table, which is what lets `g:flag = 1` keep the
    /// reference the project is owed.
    #[test]
    fn no_name_is_one_character_long() {
        assert!(NAMES.iter().all(|(whole, _)| whole.len() > 1));
    }

    /// A command Vim answers to on one letter keeps its name here, with
    /// that prefix recorded. `MIN_ABBREV` refuses the one-letter word
    /// at the lookup instead, so `has("edit")` stays true while `e`
    /// names nothing.
    #[test]
    fn every_prefix_fits_the_name_it_shortens() {
        assert!(NAMES
            .iter()
            .all(|(whole, least)| *least >= 1 && *least <= whole.len()));
    }

    #[test]
    fn a_full_command_name_is_its_own_canonical_form() {
        assert_eq!(canonical("autocmd"), Some("autocmd"));
    }

    #[test]
    fn an_abbreviation_answers_the_command_it_names() {
        assert_eq!(canonical("au"), Some("autocmd"));
        assert_eq!(canonical("bwipe"), Some("bwipeout"));
        assert_eq!(canonical("echom"), Some("echomsg"));
    }

    #[test]
    fn an_abbreviation_shorter_than_the_whole_name_is_a_command() {
        assert_eq!(canonical("bwip"), Some("bwipeout"));
    }

    #[test]
    fn a_word_of_one_character_is_no_command() {
        assert_eq!(canonical("e"), None);
    }

    #[test]
    fn a_word_that_is_no_command_answers_nothing() {
        assert_eq!(canonical("Recover"), None);
        assert_eq!(canonical("fountain"), None);
    }
}
